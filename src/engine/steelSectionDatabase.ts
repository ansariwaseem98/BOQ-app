// Project custom section store
let customProjectSections: SteelSectionItem[] = [];

export function getCustomSections(): SteelSectionItem[] {
  return [...customProjectSections];
}

export function registerCustomSection(section: SteelSectionItem): void {
  customProjectSections = [
    ...customProjectSections.filter((s) => s.sectionId !== section.sectionId),
    { ...section, isCustom: true },
  ];
}

export function removeCustomSection(sectionId: string): void {
  customProjectSections = customProjectSections.filter((s) => s.sectionId !== sectionId);
}

export function getAllAvailableSections(): SteelSectionItem[] {
  return [...MASTER_STEEL_SECTIONS, ...customProjectSections];
}

/**
 * Deterministic Section Lookup:
 * Matches normalized designation e.g. "UB 610x229x101", "ISMB 450", "Z200x65x2.0"
 * Returns null if not found (strictly NO FABRICATION).
 */
export function lookupSteelSection(designation: string): SteelSectionItem | null {
  if (!designation || !designation.trim()) return null;
  const clean = designation.replace(/\s+/g, ' ').trim().toLowerCase();

  const all = getAllAvailableSections();
  const directMatch = all.find(
    (s) => s.designation.toLowerCase() === clean || s.sectionId.toLowerCase() === clean
  );
  if (directMatch) return directMatch;

  // Normalized matching (e.g. without spaces, hyphens, case-insensitive)
  const normClean = clean.replace(/[\s\-_x*×]/g, '');
  const match = all.find((s) => {
    const sNorm = s.designation.toLowerCase().replace(/[\s\-_x*×]/g, '');
    return sNorm === normClean;
  });

  return match || null;
}
